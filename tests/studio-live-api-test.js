const fs=require('fs'),assert=require('assert');
assert.strictEqual(fs.existsSync('api/studio-live-prepare.js'),false,'não cria 13ª função serverless');
assert.strictEqual(fs.existsSync('api/studio-live-state.js'),false,'não cria 14ª função serverless');
const news=fs.readFileSync('api/news.js','utf8');
const vercel=JSON.parse(fs.readFileSync('vercel.json','utf8'));
assert.ok(news.includes('studio_live_action'),'api/news roteia ações AO VIVO');
assert.ok(news.includes('buildStudioBlock'),'prepare usa roteiro determinístico');
assert.ok(news.includes('createTurnVideo'),'prepare cria turnos no provider server-only');
assert.ok(news.includes('verifyJob'),'state valida token assinado');
assert.ok(!news.includes('process.env.HEYGEN_API_KEY'),'api/news não lê a chave diretamente');
const rewrites=Object.fromEntries((vercel.rewrites||[]).map(r=>[r.source,r.destination]));
assert.strictEqual(rewrites['/api/studio-live-prepare'],'/api/news?studio_live_action=prepare');
assert.strictEqual(rewrites['/api/studio-live-state'],'/api/news?studio_live_action=state');
console.log('OK studio-live-api');
